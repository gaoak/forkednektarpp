/**
 * @file AdvDiffFusedElmtBlockOp.hpp
 * @brief Per-block interface of the fused element-local advection-diffusion
 * operator.
 *
 * @details
 * See AdvDiffFusedElmtOp.hpp for what the operator computes. The block's
 * shape, sizes and trace packing are those of the advection operator
 * (SolverCore/Advection/AdvectionFusedElmt/AdvectionFusedElmtBlockOp.hpp),
 * which this class derives from; it adds the viscous outputs. The
 * implementations are detail::AdvDiffFusedElmtBlockOpImpl, templated on the
 * execution space, the implementation, the data type and the flux policy:
 * AdvDiffFusedElmtBlockOpSerialAVXSumFac.hpp on the host (SumFac) and
 * AdvDiffFusedElmtBlockOpDeviceSumFacTOP.hpp on the device (SumFacTOP). Their
 * registrations are generated by ADD_POLICY_ELMT_BLOCK_OPERATOR
 * (cmake/NektarCommon.cmake) in the code that supplies the policy, under the
 * key `name + policy name + execution space + implementation`.
 */

#pragma once

#include <SolverCore/Advection/AdvectionFusedElmt/AdvectionFusedElmtBlockOp.hpp>

#include <memory>
#include <string>
#include <vector>

namespace Nektar::SolverCore
{

/**
 * @brief Base class of the per-block fused element-local advection-diffusion
 * operators: the advection block operator's state, trace and derivative
 * inner products, with the outward normal viscous flux on the traces and the
 * gradient on the traces of listed elements through ApplyFusedElmt().
 *
 * @tparam TData  Floating-point type of the field data.
 */
template <typename TData>
class AdvDiffFusedElmtBlockOp : public AdvectionFusedElmtBlockOp<TData>
{
public:
    /// Block-operator base name; the factory key appends the policy's name,
    /// the execution space and the implementation.
    static inline const std::string name = "BlockAdvDiffFusedElmt";

    /**
     * @brief Create the block operator registered for the policy
     * @p policyName in execution space @p execStr and implementation
     * @p implStr.
     *
     * @return The block operator, or null when none is registered under the
     * key or the one registered does not take the block.
     */
    static std::shared_ptr<AdvDiffFusedElmtBlockOp<TData>> Create(
        const unsigned int block_idx,
        const LocalRegions::ExpansionSharedPtr &exp,
        LibUtilities::NekDataWarehouseSharedPtr dataWarehouse,
        const std::string &policyName, const std::string &execStr,
        const std::string &implStr)
    {
        return detail::CreateFusedElmtBlockOp<AdvDiffFusedElmtBlockOp<TData>,
                                              TData>(
            name + policyName + execStr + implStr, block_idx, exp,
            dataWarehouse);
    }

    /**
     * @brief The fused pass over the block's element groups.
     *
     * @param   state          The state, one component per variable.
     * @param   aux            The policy's auxiliary fields, or null when it
     *                         has none.
     * @param   trace          Out: the state on the element-local traces.
     * @param   traceNormVisc  Out: each element's outward normal viscous flux
     *                         on its traces.
     * @param   gradTrace      Out, or null: the gradient on the traces of the
     *                         elements SetGradientTraceElements() lists, in
     *                         list order, component `n * NDIM + d` the
     *                         derivative of variable n along direction d.
     * @param   out            Out: the negated derivative inner products of
     *                         the flux vector `viscFlux - advFlux`.
     */
    void ApplyFusedElmt(
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &state,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> *aux,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &trace,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &traceNormVisc,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> *gradTrace,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &out)
    {
        v_ApplyAdvDiffFusedElmt(state, aux, trace, traceNormVisc, gradTrace,
                                out);
    }

    /// The elements of the block, sorted, whose gradient trace
    /// ApplyFusedElmt() writes, in this order; empty writes none. What
    /// depends on them alone is built here, for the block's @p nelmtPad
    /// elements, padding included.
    void SetGradientTraceElements(const std::vector<unsigned int> &elements,
                                  const size_t nelmtPad)
    {
        v_SetGradientTraceElements(elements, nelmtPad);
    }

protected:
    /// The block's shape, sizes and trace packing, as the advection block
    /// operator reads them.
    AdvDiffFusedElmtBlockOp(
        const unsigned int block_idx,
        const LocalRegions::ExpansionSharedPtr &exp,
        LibUtilities::NekDataWarehouseSharedPtr dataWarehouse)
        : AdvectionFusedElmtBlockOp<TData>(block_idx, exp, dataWarehouse)
    {
    }

    ~AdvDiffFusedElmtBlockOp() override = default;

    /// The advection pass alone, without the viscous outputs, is refused.
    void v_ApplyFusedElmt(
        [[maybe_unused]] LibUtilities::BlockAccessor<TData, FieldState::Phys>
            &state,
        [[maybe_unused]] LibUtilities::BlockAccessor<TData, FieldState::Phys>
            *aux,
        [[maybe_unused]] LibUtilities::BlockAccessor<TData, FieldState::Phys>
            &trace,
        [[maybe_unused]] LibUtilities::BlockAccessor<TData, FieldState::Phys>
            &out) final
    {
        NEKERROR(ErrorUtil::efatal,
                 "The advection-diffusion pass writes the normal viscous flux "
                 "on the traces too: call its ApplyFusedElmt().");
    }

    virtual void v_ApplyAdvDiffFusedElmt(
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &state,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> *aux,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &trace,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &traceNormVisc,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> *gradTrace,
        LibUtilities::BlockAccessor<TData, FieldState::Phys> &out) = 0;

    virtual void v_SetGradientTraceElements(
        const std::vector<unsigned int> &elements, size_t nelmtPad) = 0;
};

} // namespace Nektar::SolverCore
