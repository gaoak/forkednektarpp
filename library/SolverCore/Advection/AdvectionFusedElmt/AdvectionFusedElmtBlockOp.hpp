/**
 * @file AdvectionFusedElmtBlockOp.hpp
 * @brief Per-block interface of the fused element-local advection operator.
 *
 * @details
 * See AdvectionFusedElmtOp.hpp for what the operator computes. The
 * implementations are detail::AdvectionFusedElmtBlockOpImpl, templated on
 * the execution space, the implementation, the data type and the flux
 * policy: AdvectionFusedElmtBlockOpSerialAVXSumFac.hpp on the host (SumFac)
 * and AdvectionFusedElmtBlockOpDeviceSumFacTOP.hpp on the device
 * (SumFacTOP). Their registrations are generated by
 * ADD_POLICY_ELMT_BLOCK_OPERATOR (cmake/NektarCommon.cmake) in the code that
 * supplies the policy, under the key `name + policy name + execution space +
 * implementation`.
 *
 * The block's shape, point counts and trace packing are what every fused
 * element-local pass needs, so this class is also the base of the
 * advection-diffusion block operators (AdvDiffFusedElmtBlockOp), which add
 * the viscous outputs.
 */

